// ============================================================================
// Helpers
// ============================================================================

fn g1(env: &Env, b: &[u8; 64]) -> BytesN<64> {
    BytesN::from_array(env, b)
}
fn g2(env: &Env, b: &[u8; 128]) -> BytesN<128> {
    BytesN::from_array(env, b)
}
fn fr(env: &Env, b: &[u8; 32]) -> BytesN<32> {
    BytesN::from_array(env, b)
}

/// Build the fixed verification key (α, β, γ, δ, IC) shared by all tests.
fn vk(env: &Env) -> (BytesN<64>, BytesN<128>, BytesN<128>, BytesN<128>, Vec<BytesN<64>>) {
    let ic: Vec<BytesN<64>> = vec![env, g1(env, &VK_IC0), g1(env, &VK_IC1)];
    (
        g1(env, &VK_ALPHA),
        g2(env, &VK_BETA),
        g2(env, &VK_GAMMA),
        g2(env, &VK_DELTA),
        ic,
    )
}

// ============================================================================
// Positive path — a genuinely valid proof must verify.
// ============================================================================

#[test]
fn test_valid_proof_verifies() {
    let env = Env::default();
    let id = env.register(Verifier, ());
    let client = VerifierClient::new(&env, &id);

    let (alpha, beta, gamma, delta, ic) = vk(&env);
    let public: Vec<BytesN<32>> = vec![&env, fr(&env, &PUBLIC_INPUT_0)]; // c = 33

    let ok = client.verify(
        &g1(&env, &PROOF_A),
        &g2(&env, &PROOF_B),
        &g1(&env, &PROOF_C),
        &alpha,
        &beta,
        &gamma,
        &delta,
        &ic,
        &public,
    );
    assert!(ok, "valid Groth16 proof must verify");
}

// ============================================================================
// Negative path — same valid proof, WRONG public input (c = 34) must fail.
// (All encodings remain valid points/scalars, so this exercises the pairing
//  equation itself, not an input-validation trap.)
// ============================================================================

#[test]
fn test_wrong_public_input_rejected() {
    let env = Env::default();
    let id = env.register(Verifier, ());
    let client = VerifierClient::new(&env, &id);

    let (alpha, beta, gamma, delta, ic) = vk(&env);

    let mut wrong = PUBLIC_INPUT_0;
    wrong[31] = 0x22; // 34 instead of 33
    let public: Vec<BytesN<32>> = vec![&env, fr(&env, &wrong)];

    let ok = client.verify(
        &g1(&env, &PROOF_A),
        &g2(&env, &PROOF_B),
        &g1(&env, &PROOF_C),
        &alpha,
        &beta,
        &gamma,
        &delta,
        &ic,
        &public,
    );
    assert!(!ok, "proof must NOT verify against the wrong public input");
}

// ============================================================================
// Negative path — zero proof (points at infinity) against the REAL vk fails.
// ============================================================================

#[test]
fn test_zero_proof_rejected() {
    let env = Env::default();
    let id = env.register(Verifier, ());
    let client = VerifierClient::new(&env, &id);

    let (alpha, beta, gamma, delta, ic) = vk(&env);
    let public: Vec<BytesN<32>> = vec![&env, fr(&env, &PUBLIC_INPUT_0)];

    let zero_g1 = BytesN::from_array(&env, &[0u8; 64]);
    let zero_g2 = BytesN::from_array(&env, &[0u8; 128]);

    let ok = client.verify(
        &zero_g1, &zero_g2, &zero_g1, &alpha, &beta, &gamma, &delta, &ic, &public,
    );
    assert!(!ok, "all-zero proof must not verify against a real vk");
}
